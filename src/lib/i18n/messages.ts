type DeepStringify<T> = {
  [K in keyof T]: T[K] extends string ? string : DeepStringify<T[K]>;
};

/** Arborescence i18n — `fr` est la source de vérité des clés. */
export type MessageTree = DeepStringify<(typeof messages)["fr"]>;

export function tPath(
  tree: MessageTree,
  path: string,
  params?: Record<string, string | number>,
): string {
  const resolve = (root: unknown): string | undefined => {
    let cur: unknown = root;
    for (const p of path.split(".")) {
      if (cur && typeof cur === "object" && p in (cur as object)) {
        cur = (cur as Record<string, unknown>)[p];
      } else {
        return undefined;
      }
    }
    return typeof cur === "string" ? cur : undefined;
  };

  let text = resolve(tree) ?? resolve(messages.fr) ?? path;
  if (params) {
    text = Object.entries(params).reduce(
      (s, [k, v]) => s.replace(new RegExp(`{{${k}}}`, "g"), String(v)),
      text,
    );
  }
  return text;
}
